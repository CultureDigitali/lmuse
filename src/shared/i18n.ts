export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = STRINGS[lang][key] ?? STRINGS.it[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

